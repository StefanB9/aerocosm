//! Reading crate versions from `Cargo.lock`.

/// The version of the first `[[package]]` named exactly `name`, if any.
///
/// `Cargo.lock` is TOML, but its package entries always list `name` then
/// `version` on their own lines, so a line scan is enough and avoids a TOML
/// dependency.
pub(crate) fn locked_version<'a>(lock: &'a str, name: &str) -> Option<&'a str> {
    let mut lines = lock.lines().map(str::trim);
    while let Some(line) = lines.next() {
        if quoted_value(line, "name") == Some(name) {
            return lines.next().and_then(|next| quoted_value(next, "version"));
        }
    }
    None
}

/// The string value of a `key = "value"` line.
fn quoted_value<'a>(line: &'a str, key: &str) -> Option<&'a str> {
    line.strip_prefix(key)?
        .trim_start()
        .strip_prefix('=')?
        .trim()
        .strip_prefix('"')?
        .strip_suffix('"')
}

#[cfg(test)]
mod tests {
    use proptest::prelude::*;

    use super::*;

    const LOCK: &str = r#"
# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "wasm-bindgen"
version = "0.2.130"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "wasm-bindgen-macro"
version = "0.2.130"

[[package]]
name = "getrandom"
version = "0.3.4"

[[package]]
name = "getrandom"
version = "0.4.3"
"#;

    #[test]
    fn test_locked_version_finds_exact_package() {
        assert_eq!(locked_version(LOCK, "wasm-bindgen"), Some("0.2.130"));
    }

    #[test]
    fn test_locked_version_ignores_prefix_matches_and_missing() {
        assert_eq!(locked_version(LOCK, "wasm"), None);
        assert_eq!(locked_version(LOCK, "serde"), None);
    }

    #[test]
    fn test_locked_version_returns_first_of_duplicates() {
        assert_eq!(locked_version(LOCK, "getrandom"), Some("0.3.4"));
    }

    proptest! {
        #![proptest_config(ProptestConfig::with_cases(1000))]

        #[test]
        fn test_locked_version_round_trip(name in "[a-z][a-z0-9_-]{0,20}", version in "[0-9]{1,3}\\.[0-9]{1,3}\\.[0-9]{1,3}") {
            let lock = format!("[[package]]\nname = \"{name}\"\nversion = \"{version}\"\n");
            prop_assert_eq!(locked_version(&lock, &name), Some(version.as_str()));
        }
    }
}
